import {test,expect} from '@playwright/test';

test('garden rest grows the world only after explicit completion and survives reload',async({page})=>{
 await page.route('https://api.open-meteo.com/**',route=>route.abort());
 await page.clock.install({time:new Date('2026-11-17T04:00:00Z')});
 await page.goto('/');
 await expect(page.getByRole('heading',{name:'半日闲',exact:true})).toBeVisible();
 await expect(page.getByText('今日歇息 0 次 · 累计 0 次')).toBeAttached();
 await page.getByRole('button',{name:'唤醒身体 →',exact:true}).click();
 await expect(page.getByRole('dialog')).toBeVisible();
 await page.getByRole('button',{name:'查看步骤',exact:true}).click();
 await page.getByRole('button',{name:'开始计时',exact:true}).click();
 await page.clock.runFor(5000);
 await page.getByRole('button',{name:'暂停计时',exact:true}).click();
 const paused=await page.getByRole('timer').textContent();
 await page.clock.runFor(35000);
 await expect(page.getByRole('timer')).toHaveText(paused!);
 await page.keyboard.press('Escape');
 await expect(page.getByRole('dialog')).toBeHidden();
 await page.getByRole('button',{name:'继续这段休息 →',exact:true}).click();
 await page.getByRole('button',{name:'继续计时',exact:true}).click();
 await page.clock.runFor(35000);
 await expect(page.getByRole('button',{name:'我已完成，确认记录',exact:true})).toBeVisible();
 await expect(page.locator('.garden-bloom')).toHaveCount(0);
 await page.getByRole('button',{name:'我已完成，确认记录',exact:true}).click();
 await expect(page.locator('.garden-bloom')).toHaveCount(1);
 await page.getByRole('button',{name:'回到庭园',exact:true}).click();
 await page.reload();
 await expect(page.locator('.garden-bloom')).toHaveCount(1);
 await expect(page.getByText('今日歇息 1 次 · 累计 1 次')).toBeAttached();
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
});

test('landmarks lead to matching short rests, daily slips and the herb book',async({page})=>{
 await page.route('https://api.open-meteo.com/**',route=>route.abort());
 await page.clock.install({time:new Date('2026-11-17T04:00:00Z')});
 await page.goto('/');
 await page.getByRole('button',{name:'松风亭 借一眼远山',exact:true}).click();
 await page.clock.runFor(1000);
 await page.getByRole('button',{name:'借一眼远山 →',exact:true}).click();
 await expect(page.getByRole('heading',{name:'离屏看远',exact:true})).toBeVisible();
 await page.getByRole('button',{name:'歇一下',exact:true}).click();
 await page.getByRole('button',{name:'记入手记',exact:true}).click();
 await page.getByRole('button',{name:'回到庭园',exact:true}).click();
 await expect(page.locator('.garden-bloom')).toHaveCount(1);
 await page.getByRole('button',{name:'拾光轩 抽一枚今日签',exact:true}).click();
 await page.clock.runFor(1000);
 await page.getByRole('button',{name:'抽一枚今日签 →',exact:true}).click();
 await expect(page.getByRole('region',{name:'今日节气签'})).toBeVisible();
 await page.getByRole('button',{name:'抽一支',exact:true}).click();
 await page.clock.runFor(1500);
 await page.getByRole('button',{name:'揭签',exact:true}).click();
 await expect(page.locator('.slip-face')).toBeVisible();
 await page.getByRole('button',{name:'回到庭园',exact:true}).click();
 await page.getByRole('button',{name:'百草圃 看看草木',exact:true}).click();
 await page.clock.runFor(1000);
 await page.getByRole('button',{name:'看看草木 →',exact:true}).click();
 await expect(page.getByRole('button',{name:'草木册',exact:true})).toBeVisible();
});
