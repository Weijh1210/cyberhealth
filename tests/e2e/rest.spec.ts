const date=new Date('2026-11-07T04:00:00Z');
const nav=(page:Page,label:string)=>page.getByRole('navigation',{name:'主导航'}).getByRole('button',{name:label,exact:true});
const hero=(page:Page)=>page.getByRole('region',{name:'当前推荐'});
const storage=(page:Page):Promise<AppData>=>page.evaluate(()=>JSON.parse(localStorage.getItem('moyu-wellness-v1')||'{}'));
async function weather(page:Page,code=0,rain=0,at=date){
 await page.route('https://api.open-meteo.com/v1/forecast?**',route=>route.fulfill({json:{current:{time:+at/1000,weather_code:code,rain}},headers:{'access-control-allow-origin':'*'}}));
}
async function seed(page:Page,data:AppData){
 await page.addInitScript(d=>{if(!localStorage.getItem('moyu-wellness-v1'))localStorage.setItem('moyu-wellness-v1',JSON.stringify(d));},data);
}
async function open(page:Page){
 await page.goto('/');
 await expect(hero(page)).toBeVisible();
}
