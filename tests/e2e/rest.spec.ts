test('motion permission is opt-in, two shake impulses produce one stick, and reload keeps the draw',async({page},info)=>{
 await page.clock.install({time:date});
 await weather(page);
 await page.addInitScript(()=>{
  Object.defineProperty(window.DeviceMotionEvent,'requestPermission',{configurable:true,value:async()=> 'granted'});
 });
 await open(page);
 const panel=page.getByRole('region',{name:'今日节气签'});
 await panel.getByRole('button',{name:'晃动手机抽签'}).click();
 await expect(panel.getByRole('status')).toContainText('已就绪');
 async function sample(x:number){
  await page.evaluate(x=>window.dispatchEvent(new DeviceMotionEvent('devicemotion',{accelerationIncludingGravity:{x,y:0,z:9.8}})),x);
 }
 await sample(0);
 await page.clock.runFor(110);
 await sample(14);
 expect((await storage(page)).restJournal?.draws).toBeUndefined();
 await page.clock.runFor(110);
 await sample(-12);
 await expect(panel).toHaveAttribute('data-phase','drawing');
 await expect(panel.locator('.slip-flying')).toHaveCSS('animation-name','bamboo-rise');
 await page.clock.runFor(1200);
 await expect(panel.getByRole('button',{name:'揭签'})).toBeVisible();
 await page.screenshot({path:info.outputPath('stick-reveal.png'),fullPage:true});
 await panel.getByRole('button',{name:'揭签'}).click();
 await expect(panel.getByRole('heading',{name:/望远签/})).toBeVisible();
 await page.reload();
 await expect(panel.getByRole('heading',{name:/望远签/})).toBeVisible();
 expect(Object.keys((await storage(page)).restJournal!.draws)).toEqual(['2026-11-07']);
});
